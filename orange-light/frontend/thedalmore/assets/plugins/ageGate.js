	if (getCookie('ageGate_dalmore') === undefined) {
		$('#legalModalCenter_Id').modal('show');
		buildModal();
		window.onload = function () {
			window.Osano.cm.addEventListener("osano-cm-initialized", function () {
				document.getElementsByClassName('osano-cm-window')[0].style.display = 'none';
			});
		}
	}
