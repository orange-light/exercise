function buildModal() {
	var years = yearBuilder(1900);
	var yearSelect = document.getElementById('ageSelect_YY_Id');
	// ----------  自動產生出生年份
	years.forEach(function (x, i) {
		var yearOption = document.createElement('option');
		yearOption.value = x;
		if (x == 'default') {
			yearOption.selected = true;
		}
		yearOption.appendChild(document.createTextNode(x));
		yearSelect.appendChild(yearOption);
	});
	var months = monthBuilder(1);
	var monthSelect = document.getElementById('ageSelect_MM_Id');
	// ----------  自動產生出生月份
	months.forEach(function (x, i) {
		var monthOption = document.createElement('option');
		monthOption.value = x;
		if (x == 'default') {
			monthOption.selected = true;
		}
		monthOption.appendChild(document.createTextNode(x));
		monthSelect.appendChild(monthOption);
	});
	var message = document.getElementById('ageGateLegalAgeText_Id');
	var enterButton = document.getElementById('enterButton_Id');
	//------------ 自動判斷正確年份的正確日期
	$('#ageSelect_MM_Id').change(function () {
		var year = $('#ageSelect_YY_Id');
		var month = $('#ageSelect_MM_Id');
		var day = $('#ageSelect_DD_Id');

		if (year.val() == '' || month.val() == '') {
			return false;
		}

		var days = getDays(year.val(), month.val());
		var options = [];

		for (var i = 1; i <= days; i++) {
			options.push('<option value="' + i + '">' + i + '</option>');
		}
		// options = options.reverse();
		day.append(options.join("\n"));
	}).trigger('change');
	function checkAge() {
		var birthday_year = $('#ageSelect_YY_Id');
		var birthday_month = $('#ageSelect_MM_Id');
		var birthday_day = $('#ageSelect_DD_Id');
		var checkBokIsChecked = $('#legalCheckbox_Id').prop('checked');
		if (birthday_year.val() == null || birthday_month.val() == null || birthday_day.val() == null) {
			message.classList.add('text-danger', 'h5');
			updateMessage('請選擇您的出生年月日');
		} else {
			if (getAge(new Date(birthday_year.val(), birthday_month.val() - 1, birthday_day.val())) >= 18) {
				if (checkBokIsChecked) {
					message.classList.remove('text-danger', 'h5');
					updateMessage('未滿十八歲者，禁止飲酒');
					setCookieYear('ageGate_dalmore');
					setCookieYear('AgeVerify_dalmore');
					$('#legalModalCenter_Id').modal('hide');
				} else {
					message.classList.add('text-danger', 'h5');
					updateMessage('您尚未接受隱私條款');
				}
			} else {
				message.classList.add('text-danger', 'h5');
				updateMessage('很抱歉，您尚未達到台灣法定飲酒年齡，不得進入本站');
			}
		}
	}
	function updateMessage(msg) {
		var text = document.createTextNode(msg);
		if (message.hasChildNodes()) {
			message.removeChild(message.childNodes[0]);
		}
		message.appendChild(text);
	}
	enterButton.onclick = checkAge;
}
