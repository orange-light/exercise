var yearBuilder = function yearBuilder(startYear) {
	var currentYear = new Date().getFullYear(),
		years = [];
	startYear = startYear || 1980;
	while (startYear <= currentYear) {
		years.push(startYear++);
	}
	years = years.reverse();
	return years;
};
//創建月份Array(從上面延伸過來的改寫)
var monthBuilder = function monthBuilder(startMonth) {
	var currentMonth = 12,
		months = [];
	startMonth = startMonth || 12;
	while (startMonth <= currentMonth) {
		months.push(startMonth++);
	}
	// months = months.reverse();
	return months;
};
var setCookieYear = function setCookie(name) {
	var d = new Date();
	d.setTime(d.getTime() + (365 * 24 * 60 * 60 * 1000));
	document.cookie = name + "=true; expires=" + d.toGMTString();

};
var getCookie = function getCookie(name) {
	var value = "; " + document.cookie;
	var parts = value.split("; " + name + "=");
	if (parts.length == 2) return parts.pop().split(";").shift();
};
